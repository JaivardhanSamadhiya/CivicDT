"use client";
import { Check, LoaderCircle, Circle, AlertCircle } from "lucide-react";
export const stages = [
  "Document ingestion",
  "Proposal extraction",
  "Input validation",
  "Scenario generation",
  "Model execution",
  "Comparison",
  "Decision brief",
];
export type StageStatus = "pending" | "running" | "done" | "review" | "error";
export function Pipeline({ statuses }: { statuses: StageStatus[] }) {
  return (
    <aside className="card pipeline">
      <div className="panel-heading">
        <h3>Analysis pipeline</h3>
        <span className="soft-badge">LIVE STAGES</span>
      </div>
      <p className="muted small-text">
        Stages reflect completed work. Review comes before modeling.
      </p>
      <ol>
        {stages.map((stage, i) => {
          const status = statuses[i] ?? "pending";
          const Icon =
            status === "done"
              ? Check
              : status === "running"
                ? LoaderCircle
                : status === "error"
                  ? AlertCircle
                  : Circle;
          return (
            <li key={stage} className={`stage stage-${status}`}>
              <span className="stage-icon">
                <Icon
                  size={14}
                  className={status === "running" ? "spin" : ""}
                />
              </span>
              <div>
                <strong>{stage}</strong>
                <small>
                  {status === "done"
                    ? "Complete"
                    : status === "running"
                      ? "Executing"
                      : status === "review"
                        ? "Awaiting your review"
                        : status === "error"
                          ? "Needs attention"
                          : "Pending"}
                </small>
              </div>
            </li>
          );
        })}
      </ol>
      <div className="pipeline-note">
        No quantitative result is generated by an LLM.
      </div>
    </aside>
  );
}
